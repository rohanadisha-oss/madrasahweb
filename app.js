// টাইপিং এফেক্ট ইঞ্জিন
let typingInterval;
function startTypingEffect() {
  const phrases = siteData.heroPhrases && siteData.heroPhrases.length > 0 
    ? siteData.heroPhrases 
    : ["আধুনিক প্রযুক্তি ও নৈতিক শিক্ষার সমন্বয়"];
  const el = document.querySelector('.typing-target');
  if (!el) return;

  let phraseIdx = 0, charIdx = 0, isDeleting = false;
  clearInterval(typingInterval);

  function type() {
    const current = phrases[phraseIdx];
    if (isDeleting) {
      el.textContent = current.substring(0, charIdx - 1);
      charIdx--;
    } else {
      el.textContent = current.substring(0, charIdx + 1);
      charIdx++;
    }

    let speed = isDeleting ? 40 : 80;
    if (!isDeleting && charIdx === current.length) {
      speed = 1800;
      isDeleting = true;
    } else if (isDeleting && charIdx === 0) {
      isDeleting = false;
      phraseIdx = (phraseIdx + 1) % phrases.length;
      speed = 400;
    }
    typingInterval = setTimeout(type, speed);
  }
  type();
}

// সংখ্যা কাউন্টার অ্যানিমেশন
function startCounterAnimation() {
  const counters = document.querySelectorAll('.counter');
  counters.forEach(c => {
    const target = +c.getAttribute('data-target');
    let count = 0;
    const speed = Math.max(1, target / 40);

    const updateCount = () => {
      count += speed;
      if (count < target) {
        c.innerText = Math.ceil(count);
        setTimeout(updateCount, 25);
      } else {
        c.innerText = target;
      }
    };
    updateCount();
  });
}

function render(key) {
  activeTab = key;
  if (pages[key]) {
    stage.innerHTML = pages[key]();
  }

  btns.forEach(b => {
    b.classList.toggle('active', b.dataset.page === key);
  });

  if (key === 'home') {
    startTypingEffect();
    startCounterAnimation();
  }

  if (key === 'contact') {
    const form = document.getElementById('contactForm');
    form.addEventListener('submit', (e) => {
      e.preventDefault();
      const n = document.getElementById('name').value;
      document.getElementById('resp').innerHTML = `
        <div style="background: rgba(0, 242, 254, 0.1); border: 1px solid rgba(0, 242, 254, 0.3); color: var(--cyan); padding: 0.8rem; border-radius: 8px;">
          ধন্যবাদ <strong>${n}</strong>! আপনার বার্তাটি পাঠানো হয়েছে।
        </div>
      `;
      form.reset();
    });
  }

  if (key === 'grammar') {
    document.querySelectorAll('.acc-title').forEach(title => {
      title.addEventListener('click', () => {
        const body = title.nextElementSibling;
        body.style.display = body.style.display === 'block' ? 'none' : 'block';
      });
    });
  }
}

btns.forEach(b => {
  b.addEventListener('click', () => render(b.getAttribute('data-page')));
});

