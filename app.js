(function initBubbles() {
  const canvas = document.getElementById('bubble-canvas');
  if (!canvas) return;

  const ctx = canvas.getContext('2d');
  let particlesArray = [];
  const colors = ['#00f2fe', '#4facfe', '#9d4edd', '#ffffff', '#38bdf8'];

  function resizeCanvas() {
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
  }
  window.addEventListener('resize', resizeCanvas);
  resizeCanvas();

  class Particle {
    constructor(x, y) {
      this.x = x;
      this.y = y;
      this.size = Math.random() * 12 + 6;
      this.speedX = (Math.random() - 0.5) * 4;
      this.speedY = (Math.random() - 0.5) * 4;
      this.color = colors[Math.floor(Math.random() * colors.length)];
      this.opacity = 1;
    }

    update() {
      this.x += this.speedX;
      this.y += this.speedY;
      if (this.size > 0.3) this.size -= 0.15;
      this.opacity -= 0.02;
    }

    draw() {
      ctx.save();
      ctx.globalAlpha = Math.max(0, this.opacity);
      ctx.beginPath();
      ctx.arc(this.x, this.y, Math.max(0.1, this.size), 0, Math.PI * 2);
      ctx.fillStyle = this.color;
      ctx.shadowBlur = 15;
      ctx.shadowColor = this.color;
      ctx.fill();
      ctx.restore();
    }
  }

  function createBubbles(x, y, count = 4) {
    for (let i = 0; i < count; i++) particlesArray.push(new Particle(x, y));
  }

  window.addEventListener('mousemove', (e) => createBubbles(e.clientX, e.clientY, 2));
  window.addEventListener('touchmove', (e) => {
    for (let i = 0; i < e.touches.length; i++) createBubbles(e.touches[i].clientX, e.touches[i].clientY, 4);
  }, { passive: true });

  function animateBubbles() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    for (let i = 0; i < particlesArray.length; i++) {
      particlesArray[i].update();
      particlesArray[i].draw();
      if (particlesArray[i].size <= 0.3 || particlesArray[i].opacity <= 0) {
        particlesArray.splice(i, 1);
        i--;
      }
    }
    requestAnimationFrame(animateBubbles);
  }
  animateBubbles();
})();

